"""Parametrized m x m interferometer unitaries for the photonic QCBM.

Convention (paper Eq. (1), original code): U acts on single-photon mode
amplitudes, column j is the image of input mode j. The n-photon output
distribution for input modes S is governed by the submatrix U[:, S].

Ansätze
-------
haar
    Real vector of length 2 m^2 -> complex matrix -> QR with the diag(R)
    phase fix (paper §4.1, "Haar-compatible"). Normal(0, 1) parameters give
    Haar-distributed unitaries.
clements, butterfly, mzi3
    m(m-1)/2 two-mode MZIs (theta, phi) applied to rows of U in mesh order,
    then a layer of output phases gamma (length m). Parameter vector layout:
    [mzi params flattened (row-major, (M, 2)), gammas].

Deviations from the original code (see LOG.md "Reproducibility Assessment"):
- complex128 everywhere (the original builds meshes in complex64);
- ``butterfly_variant="corrected"`` replaces MZIs whose pair indices exceed
  m - 1 (m not a power of two, D3) by the identity, which keeps U unitary.
  ``"reference"`` reproduces the original code, including JAX's clamped reads
  and dropped out-of-range writes.
"""

from __future__ import annotations

from functools import partial

import jax
import jax.numpy as jnp
import numpy as np
from jax import lax

jax.config.update("jax_enable_x64", True)

MESH_ANSATZE = ("clements", "butterfly", "mzi3")
ANSATZE = ("haar",) + MESH_ANSATZE
BUTTERFLY_VARIANTS = ("reference", "corrected")


def num_parameters(m: int, ansatz: str) -> int:
    """Return the length of the parameter vector of an ansatz.

    Parameters
    ----------
    m : int
        Number of optical modes.
    ansatz : str
        One of ``ANSATZE``.

    Returns
    -------
    int
        2 m^2 for ``haar``; m(m-1) + m = m^2 for mesh ansätze.
    """
    if ansatz == "haar":
        return 2 * m * m
    if ansatz in MESH_ANSATZE:
        return m * (m - 1) + m
    raise ValueError(f"Unknown ansatz {ansatz!r}; expected one of {ANSATZE}.")


def clements_pairs(m: int) -> np.ndarray:
    """Mode pairs of the rectangular (Clements) mesh, in application order."""
    pattern = []
    for layer in range(m):
        start = layer % 2
        for i in range(start, m - 1, 2):
            pattern.append((i, i + 1))
    return np.asarray(pattern, dtype=np.int64)


def butterfly_pairs(m: int) -> np.ndarray:
    """Mode pairs of the butterfly mesh as generated by the original code.

    Layer k uses stride s = lowest set bit of (k + 1) and m/2 pairs
    (i, i + s). For m not a power of two some indices exceed m - 1 (D3).
    """
    layers = []
    for k in range(m - 1):
        stride = (k + 1) & -(k + 1)
        pair_index = np.arange(m // 2)
        left = pair_index % stride + 2 * stride * (pair_index // stride)
        layers.append(np.stack([left, left + stride], axis=1))
    return np.concatenate(layers).astype(np.int64)


def mesh_pairs(m: int, ansatz: str) -> np.ndarray:
    """Return the (M, 2) mode-pair array of a mesh ansatz."""
    if ansatz in ("clements", "mzi3"):
        return clements_pairs(m)
    if ansatz == "butterfly":
        return butterfly_pairs(m)
    raise ValueError(f"No mesh pattern for ansatz {ansatz!r}.")


def _mzi(theta, phi):
    # Original code's MZI: cos(theta), not the paper's cos(theta'/2) (D1).
    return jnp.array(
        [
            [jnp.exp(1j * phi) * jnp.cos(theta), -jnp.sin(theta)],
            [jnp.exp(1j * phi) * jnp.sin(theta), jnp.cos(theta)],
        ],
        dtype=jnp.complex128,
    )


def _mzi3(theta, phi):
    return jnp.array(
        [
            [
                jnp.exp(1j * phi) * jnp.sin(theta / 2) + 1j * jnp.cos(theta / 2),
                1j * jnp.exp(1j * phi) * jnp.sin(theta / 2) + jnp.cos(theta / 2),
            ],
            [
                jnp.exp(1j * phi) * jnp.cos(theta / 2) - 1j * jnp.sin(theta / 2),
                1j * jnp.exp(1j * phi) * jnp.cos(theta / 2) - jnp.sin(theta / 2),
            ],
        ],
        dtype=jnp.complex128,
    ) / jnp.sqrt(2.0)


def _apply_mesh(mzi_params, gammas, pairs, valid, m, block_fn):
    identity2 = jnp.eye(2, dtype=jnp.complex128)

    def step(U, data):
        (theta, phi), (i, j), is_valid = data
        B = jnp.where(is_valid, block_fn(theta, phi), identity2)
        row_i = U[i, :]
        row_j = U[j, :]
        U = U.at[i, :].set(B[0, 0] * row_i + B[0, 1] * row_j)
        U = U.at[j, :].set(B[1, 0] * row_i + B[1, 1] * row_j)
        return U, None

    U0 = jnp.eye(m, dtype=jnp.complex128)
    U_mesh, _ = lax.scan(step, U0, (mzi_params, pairs, valid))
    return jnp.exp(1j * gammas)[:, None] * U_mesh


@partial(jax.jit, static_argnames=("m",))
def haar_unitary(params: jnp.ndarray, m: int) -> jnp.ndarray:
    """QR-based Haar-compatible unitary from a real vector of length 2 m^2."""
    z = params[: m * m].reshape(m, m) + 1j * params[m * m : 2 * m * m].reshape(m, m)
    q, r = jnp.linalg.qr(z)
    d = jnp.diag(r)
    d = jnp.where(jnp.abs(d) > 0, d / jnp.abs(d), 1.0 + 0j)
    return q * jnp.conj(d)[None, :]


def split_mesh_params(params: jnp.ndarray, m: int):
    """Split a packed mesh vector into ((M, 2) MZI params, (m,) output phases)."""
    num_mzi = m * (m - 1) // 2
    return params[: 2 * num_mzi].reshape(num_mzi, 2), params[
        2 * num_mzi : 2 * num_mzi + m
    ]


def pack_mesh_params(mzi_params: jnp.ndarray, gammas: jnp.ndarray) -> jnp.ndarray:
    """Inverse of ``split_mesh_params``."""
    return jnp.concatenate([jnp.ravel(mzi_params), jnp.ravel(gammas)])


def make_unitary_fn(m: int, ansatz: str, butterfly_variant: str = "reference"):
    """Return a jitted ``params -> U`` function for one ansatz.

    Parameters
    ----------
    m : int
        Number of modes.
    ansatz : str
        One of ``ANSATZE``.
    butterfly_variant : str
        ``"reference"`` (original code, D3) or ``"corrected"``. Only used for
        the butterfly ansatz. Default value is "reference".

    Returns
    -------
    Callable
        Function mapping a parameter vector of length ``num_parameters(m, ansatz)``
        to an (m, m) complex128 matrix.
    """
    if ansatz == "haar":
        return jax.jit(lambda params: haar_unitary(params, m))
    if ansatz not in MESH_ANSATZE:
        raise ValueError(f"Unknown ansatz {ansatz!r}; expected one of {ANSATZE}.")
    if butterfly_variant not in BUTTERFLY_VARIANTS:
        raise ValueError(f"butterfly_variant must be one of {BUTTERFLY_VARIANTS}.")

    pairs_np = mesh_pairs(m, ansatz)
    in_range = (pairs_np < m).all(axis=1)
    if ansatz == "butterfly" and butterfly_variant == "reference":
        # Keep every MZI; JAX clamps out-of-range reads to row m-1 and drops
        # out-of-range writes, exactly as in the original code.
        valid_np = np.ones(len(pairs_np), dtype=bool)
    else:
        valid_np = in_range
    pairs = jnp.asarray(pairs_np)
    valid = jnp.asarray(valid_np)
    block_fn = _mzi3 if ansatz == "mzi3" else _mzi

    @jax.jit
    def unitary(params):
        mzi_params, gammas = split_mesh_params(params, m)
        return _apply_mesh(mzi_params, gammas, pairs, valid, m, block_fn)

    return unitary


def unitarity_error(U: jnp.ndarray) -> float:
    """Return max |U^dagger U - I| (0 for an exactly unitary matrix)."""
    m = U.shape[0]
    return float(jnp.max(jnp.abs(jnp.conj(U.T) @ U - jnp.eye(m))))
