"""Plot and tabulate the Gurvits-backend benchmark (utils/benchmark_gurvits_backends.py).

Usage (from the paper folder)::

    python utils/plot_gurvits_benchmark.py <label> <photons_run_dir> <modes_run_dir>

Reads each run's metrics.json (no logs). Two rows (photon sweep, mode sweep) x two columns:
time per operator estimate at equal shot count, and the equal-precision cost relative to JAX,
(t_backend / t_jax) * (SE_backend / SE_jax)^2: the time a backend needs to match the standard
error JAX reaches with the same shot count. Permanents shrink quickly with n, so an absolute SE
target would not be comparable across sizes; the ratio does not depend on any target. Writes results/gurvits_backend_benchmark_<label>.{json,md,png,pdf} and copies
the figure into the first run directory.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from plot_common import RESULTS_DIR, SERIES, TEXT, plt, save, style_axes

# Color = how the problem is mapped onto the estimator; line style = sign distribution.
STYLE = {
    "jax": ("JAX (this reproduction), Rademacher", SERIES["model"][1], "-", "o"),
    "pe_matched_rad": (
        "photonic_engines, n×n A_k, Rademacher",
        SERIES["b5"][1],
        "-",
        "s",
    ),
    "pe_matched_gauss": (
        "photonic_engines, n×n A_k, Gaussian",
        SERIES["b5"][1],
        "--",
        "s",
    ),
    "pe_native_rad": (
        "photonic_engines, m×m V_k, Rademacher",
        SERIES["rbm"][1],
        "-",
        "^",
    ),
    "pe_native_gauss": (
        "photonic_engines, m×m V_k, Gaussian",
        SERIES["rbm"][1],
        "--",
        "^",
    ),
}


def load(run_dir: Path) -> dict:
    status = json.loads((run_dir / "run_status.json").read_text())
    if status["status"] != "COMPLETED":
        raise ValueError(f"{run_dir.name} is {status['status']}")
    metrics = json.loads((run_dir / "metrics.json").read_text())
    return {"run": run_dir.name, "status": status, **metrics}


def main() -> None:
    """Build the table and the figure."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("label")
    parser.add_argument("photons_run", type=Path)
    parser.add_argument("modes_run", type=Path)
    args = parser.parse_args()
    runs = {"photons": load(args.photons_run), "modes": load(args.modes_run)}
    env = runs["photons"]["status"]["environment"]

    fig, axes = plt.subplots(2, 2, figsize=(12, 8.5))
    lines = [
        f"# Gurvits estimator backends — {args.label}",
        "",
        f"Generated by `utils/plot_gurvits_benchmark.py` from `{runs['photons']['run']}` and "
        f"`{runs['modes']['run']}`. Device {env['device']}"
        + (f" ({env['cuda_device']})" if env.get("cuda_device") else "")
        + f", torch {env['torch']}, jax {env['jax']}, merlin {env['merlin']}, complex128.",
        "",
        "Quantity: K Walsh expectations <W_k> = Per(U_S† diag(1−2k) U_S) for a Haar U, Z shots each. "
        "Equal-precision cost ratio = (t_backend / t_JAX) × (SE_backend / SE_JAX)², SE = root-mean-square per-operator "
        "standard error over the K operators; > 1 means slower than JAX at equal precision. Warm-up excluded (reported).",
        "",
    ]
    for row, (sweep, xkey, xlabel) in enumerate(
        (("photons", "n", "photons n"), ("modes", "m", "modes m"))
    ):
        recs = runs[sweep]["records"]
        fixed = "m" if sweep == "photons" else "n"
        fixed_value = ", ".join(str(v) for v in sorted({r[fixed] for r in recs}))
        meta = recs[0]
        jax_ref = {r[xkey]: r for r in recs if r["backend"] == "jax"}
        for r in recs:
            ref = jax_ref[r[xkey]]
            r["equal_shot_ratio"] = (
                r["seconds_per_operator"] / ref["seconds_per_operator"]
            )
            r["equal_precision_ratio"] = (
                r["equal_shot_ratio"] * (r["rms_se"] / ref["rms_se"]) ** 2
                if ref["rms_se"] > 0
                else float("nan")
            )
        for col, (key, ylabel) in enumerate(
            (
                (
                    "seconds_per_operator",
                    f"seconds per operator, Z = {meta['n_z']} shots",
                ),
                ("equal_precision_ratio", "cost relative to JAX at equal precision"),
            )
        ):
            ax = axes[row][col]
            style_axes(ax)
            if key == "equal_precision_ratio":
                ax.axhline(1.0, color=TEXT, linewidth=0.8, linestyle=":")
            for backend, (label, color, ls, marker) in STYLE.items():
                pts = sorted((r[xkey], r[key]) for r in recs if r["backend"] == backend)
                if pts:
                    ax.plot(
                        *zip(*pts),
                        ls,
                        color=color,
                        marker=marker,
                        markersize=5,
                        linewidth=2,
                        label=label,
                    )
            ax.set_xscale("log", base=2)
            ax.set_yscale("log")
            ax.set_xlabel(xlabel, color=TEXT, fontsize=9)
            ax.set_ylabel(ylabel, color=TEXT, fontsize=9)
            ax.set_title(
                f"{'photon' if sweep == 'photons' else 'mode'} sweep at {fixed} = {fixed_value}",
                fontsize=9,
                color=TEXT,
            )
        lines += [
            f"## {sweep.capitalize()} sweep ({fixed} = {fixed_value}, K = {meta['n_ops']}, Z = {meta['n_z']})",
            "",
            "| backend | "
            + xkey
            + " | trivial ops (k = 0) | s/operator | RMS SE | ratio to JAX, equal shots | "
            "ratio to JAX, equal precision | warm-up s | max |z| vs exact |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for r in sorted(recs, key=lambda r: (list(STYLE).index(r["backend"]), r[xkey])):
            z = (
                "—"
                if r["max_abs_z_vs_exact"] is None
                else f"{r['max_abs_z_vs_exact']:.2f}"
            )
            lines.append(
                f"| {r['backend']} | {r[xkey]} | {r['trivial_operators']}/{r['n_ops']} | {r['seconds_per_operator']:.3e} | {r['rms_se']:.2e} | "
                f"{r['equal_shot_ratio']:.3g} | {r['equal_precision_ratio']:.3g} | {r['warmup_seconds']:.2f} | {z} |"
            )
        lines.append("")
    handles, labels = axes[0][0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="lower center",
        ncol=3,
        frameon=False,
        fontsize=8,
        bbox_to_anchor=(0.5, -0.04),
    )
    fig.suptitle(
        f"Gurvits/Glynn permanent estimators: JAX reproduction vs MerLin photonic_engines ({args.label})\n"
        "left: equal shot count · right: equal precision (the fair comparison) · lower is better",
        fontsize=10,
        color=TEXT,
    )
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    RESULTS_DIR.mkdir(exist_ok=True)
    stem = f"gurvits_backend_benchmark_{args.label}"
    (RESULTS_DIR / f"{stem}.json").write_text(json.dumps(runs, indent=2))
    (RESULTS_DIR / f"{stem}.md").write_text("\n".join(lines))
    paths = save(fig, args.photons_run, stem)
    print(RESULTS_DIR / f"{stem}.md", paths[-1])


if __name__ == "__main__":
    main()
