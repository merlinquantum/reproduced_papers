"""Generate the Phase 03 result tables from sweep summaries (no hand-copied numbers).

Usage::

    python papers/photonic_MMD_generative/utils/make_results_tables.py <sweep_dir> [<sweep_dir> ...]

Reads each sweep's ``summary.json`` (written by ``summarize_sweep.py`` from
``metrics.json`` files) and writes ``results/results_tables.md`` and
``results/results_tables.json``: one table per sweep, every candidate, mean ±
std (ddof=1) and n for the model and baseline metrics. Full precision is kept
in the JSON; the Markdown rounds to 3 significant digits.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parents[1]
COLUMNS = (
    ("test_mmd_estimator", "QCBM, paper estimator"),
    ("model.walsh_mmd", "QCBM, sample"),
    ("model.gaussian_mmd_raw", "QCBM, Gaussian raw"),
    ("rbm.walsh_mmd", "RBM"),
    ("rbm.gaussian_mmd_raw", "RBM, Gaussian raw"),
    ("marginal.walsh_mmd", "Marginal (B4)"),
    ("random.walsh_mmd", "Random"),
    ("test_to_test.walsh_mmd", "Test-to-test"),
    ("unitarity_error", "Unitarity error"),
    ("steps_run", "Steps"),
)


def fmt(stats: dict | None) -> str:
    if not stats:
        return "—"
    std = stats["std"]
    return (
        f"{stats['mean']:.3g} ± {std:.2g} (n={stats['n']})"
        if std is not None
        else f"{stats['mean']:.3g} (n=1)"
    )


def main() -> None:
    """Write the tables."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("sweep_dirs", type=Path, nargs="+")
    args = parser.parse_args()
    lines = [
        "# Phase 03 result tables",
        "",
        "Generated by `utils/make_results_tables.py` from each sweep's `summary.json`.",
        "Test MMD² on the test split, final parameters, mean ± std (ddof=1) over seeds.",
        "'sample' = unbiased sample-based MMD² with the run's kernel operators (same",
        "estimator for every model); 'Gaussian raw' = exact Gaussian kernel on raw counts.",
        "Values are comparable within a sweep and kernel only.",
        "",
    ]
    data = {}
    for sweep_dir in args.sweep_dirs:
        summary = json.loads((sweep_dir.resolve() / "summary.json").read_text())
        data[summary["sweep_id"]] = summary
        present = [
            (k, title)
            for k, title in COLUMNS
            if any(k in c["metrics"] for c in summary["candidates"].values())
        ]
        lines += [
            f"## {summary['sweep_id']}",
            "",
            f"Coverage: {summary['coverage']} ({summary['completed_runs']}/{summary['expected_runs']} runs). "
            f"Source: `{sweep_dir.resolve().relative_to(PAPER_DIR) if sweep_dir.resolve().is_relative_to(PAPER_DIR) else sweep_dir}`.",
            "",
            "| Candidate | " + " | ".join(t for _, t in present) + " |",
            "|---|" + "---|" * len(present),
        ]
        for candidate, entry in summary["candidates"].items():
            label = json.loads(candidate)["label"]
            lines.append(
                f"| {label} | "
                + " | ".join(fmt(entry["metrics"].get(k)) for k, _ in present)
                + " |"
            )
        lines.append("")
    out = PAPER_DIR / "results"
    (out / "results_tables.md").write_text("\n".join(lines))
    (out / "results_tables.json").write_text(json.dumps(data, indent=2))
    print(out / "results_tables.md")


if __name__ == "__main__":
    main()
