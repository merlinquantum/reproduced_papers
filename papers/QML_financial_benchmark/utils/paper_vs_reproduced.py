"""Paper-versus-reproduced table for every reproduced table item (Phase 6).

Reads ``results/phase5_comparison.csv``, ``results/phase5_differences.csv``
and ``results/e6_e7_seed0_table.csv`` (all generated by earlier phases) and
writes ``results/paper_vs_reproduced.csv`` with one row per paper value:

- ``delta`` = reproduced mean - paper value;
- ``metric_agreement``: ``yes`` when |delta| <= max(0.02, 2 x seed std) for
  AUC and Sharpe; ``n/a`` for QLIKE levels, whose test window the paper does
  not state (R15);
- ``trend_agreement``: does the local quantum - classical comparison have the
  paper's sign at p < 0.05 (seed-level t-test for Tasks 1-2, Diebold-Mariano
  for Task 3)? ``tie`` when p >= 0.05, ``reversed`` when significant with the
  opposite sign;
- ``claim_support``: the Phase 5 claim outcome.

Usage (repository root)::

    .venv/bin/python papers/QML_financial_benchmark/utils/paper_vs_reproduced.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parents[1]
RESULTS = PROJECT_DIR / "results"
AGREEMENT_FLOOR = 0.02

CLAIM_SUPPORT = {
    "C1": "UNSUPPORTED",
    "C2": "UNSUPPORTED",
    "C3": "PARTIALLY_SUPPORTED",
    "C5": "UNSUPPORTED",
    "C7": "UNSUPPORTED (KCHOL part)",
    "C9": "PARTIALLY_SUPPORTED",
}
# Task 3 row model -> (comparator for the trend, claim, claim support).
VOLATILITY_ROWS = {
    "qsvr_angle": ("svr_rbf", "C7", "UNSUPPORTED (KCHOL part)"),
    "svr_rbf": ("svr_rbf", "C7", "UNSUPPORTED (KCHOL part)"),
    "svr_linear": ("svr_linear", "C8/C10", "C8 PARTIALLY_SUPPORTED; C10 SUPPORTED"),
    "garch_sigma2": (
        "garch_sigma2",
        "C7 (paper GARCH)",
        "QSVR beats sigma2-only GARCH; loses to completed GARCH",
    ),
}
PAPER_ITEM = {"3-D": "Table IX", "7-D": "Table X", "64-D": "Table XI"}
# Table XIV, amplitude QSVR (d = 32, 5 qubits); the paper reports it loses to SVR-RBF on every ticker.
PAPER_AMPLITUDE_QLIKE = {
    "GSPC": -8.1824,
    "AAPL": -7.3065,
    "GARAN": -5.6154,
    "KCHOL": -6.1804,
}


def trend(paper_difference: float, local_difference: float, p_value: float) -> str:
    if p_value >= 0.05:
        return "tie"
    return "yes" if (paper_difference > 0) == (local_difference > 0) else "reversed"


def agreement(delta: float, std: float) -> str:
    return "yes" if abs(delta) <= max(AGREEMENT_FLOOR, 2 * std) else "no"


def classification_and_trading(
    comparison: pd.DataFrame, differences: pd.DataFrame
) -> list[dict]:
    rows = []
    pairs = {
        "test AUC (max)": (
            "leak_free:qnn",
            "leak_free:ann",
            "paper QNN",
            "paper ANN",
            "leak_free:qnn - leak_free:ann",
        ),
        "test Sharpe (max)": (
            "auc:qlstm",
            "auc:lstm",
            "paper QLSTM",
            "paper LSTM",
            "auc:qlstm - auc:lstm (sharpe)",
        ),
    }
    for (claim, setting, metric), group in comparison.groupby(
        ["claim", "setting", "metric"], sort=False
    ):
        quantum, classical, paper_quantum, paper_classical, difference_name = pairs[
            metric
        ]
        values = group.set_index("system")
        if paper_quantum not in values.index:
            continue
        local_difference = differences[
            (differences["setting"] == setting)
            & (differences["comparison"] == difference_name)
        ].iloc[0]
        paper_difference = (
            values.loc[paper_quantum, "mean"] - values.loc[paper_classical, "mean"]
        )
        trend_result = trend(
            paper_difference,
            local_difference["difference"],
            local_difference["p_value"],
        )
        item = (
            "Table XII"
            if metric.startswith("test Sharpe")
            else next(
                PAPER_ITEM[token] for token in setting.split() if token in PAPER_ITEM
            )
        )
        for system, paper_system in (
            (quantum, paper_quantum),
            (classical, paper_classical),
        ):
            local = values.loc[system]
            delta = local["mean"] - values.loc[paper_system, "mean"]
            rows.append(
                {
                    "paper_item": item,
                    "claim": claim,
                    "setting": setting,
                    "model": paper_system.removeprefix("paper "),
                    "metric": metric,
                    "paper_value": values.loc[paper_system, "mean"],
                    "reproduced_mean": local["mean"],
                    "reproduced_std": local["std"],
                    "delta": delta,
                    "metric_agreement": "n/a (diagnostic features)"
                    if "diagnostic" in setting
                    else agreement(delta, local["std"]),
                    "comparison": difference_name,
                    "paper_difference": paper_difference,
                    "local_difference": local_difference["difference"],
                    "local_p": local_difference["p_value"],
                    "trend_agreement": trend_result,
                    "claim_support": CLAIM_SUPPORT[claim],
                    "seeds": local["runs"].split("/")[0],
                    "scope": local["scope"],
                }
            )
    return rows


def volatility(comparison: pd.DataFrame, differences: pd.DataFrame) -> list[dict]:
    rows = []
    table = pd.read_csv(RESULTS / "e6_e7_seed0_table.csv")
    for setting, group in comparison[comparison["metric"] == "QLIKE (min)"].groupby(
        "setting", sort=False
    ):
        ticker = setting.split()[1]
        values = group.set_index("system")
        for model, (comparator, claim, support) in VOLATILITY_ROWS.items():
            paper_value = values.loc[f"paper {model}", "mean"]
            local = differences[
                (differences["setting"] == setting)
                & differences["comparison"].str.startswith(
                    f"QLIKE(qsvr_angle) - QLIKE({comparator})"
                )
            ].iloc[0]
            # Both differences are QSVR - comparator; negative = QSVR better.
            paper_difference = (
                values.loc["paper qsvr_angle", "mean"]
                - values.loc[f"paper {comparator}", "mean"]
            )
            rows.append(
                {
                    "paper_item": "Table XIII",
                    "claim": claim,
                    "setting": setting,
                    "model": model,
                    "metric": "QLIKE (min)",
                    "paper_value": paper_value,
                    "reproduced_mean": values.loc[model, "mean"],
                    "reproduced_std": float("nan"),
                    "delta": values.loc[model, "mean"] - paper_value,
                    "metric_agreement": "n/a (test window unstated, R15)",
                    "comparison": f"qsvr_angle - {comparator}",
                    "paper_difference": paper_difference,
                    "local_difference": local["difference"],
                    "local_p": local["p_value"],
                    "trend_agreement": trend(
                        paper_difference, local["difference"], local["p_value"]
                    ),
                    "claim_support": support,
                    "seeds": "deterministic"
                    if model == "garch_sigma2"
                    else "1 (Optuna seed 0)",
                    "scope": values.loc[model, "scope"],
                }
            )
        e7 = table[(table["exp"] == "e7") & (table["ticker"] == ticker)].set_index(
            "model"
        )
        amplitude = e7.loc["qsvr_amplitude", "qlike"]
        local_difference = amplitude - e7.loc["svr_rbf", "qlike"]
        rows.append(
            {
                "paper_item": "Table XIV",
                "claim": "C9",
                "setting": setting,
                "model": "qsvr_amplitude",
                "metric": "QLIKE (min)",
                "paper_value": PAPER_AMPLITUDE_QLIKE[ticker],
                "reproduced_mean": amplitude,
                "reproduced_std": float("nan"),
                "delta": amplitude - PAPER_AMPLITUDE_QLIKE[ticker],
                "metric_agreement": "n/a (test window unstated, R15)",
                # The paper's amplitude QSVR is behind SVR-RBF on every ticker.
                "comparison": "qsvr_amplitude - svr_rbf",
                "paper_difference": float("nan"),
                "local_difference": local_difference,
                "local_p": e7.loc["svr_rbf", "dm_qlike_p"],
                "trend_agreement": "yes"
                if e7.loc["svr_rbf", "dm_qlike_p"] < 0.05 and local_difference > 0
                else "tie"
                if e7.loc["svr_rbf", "dm_qlike_p"] >= 0.05
                else "reversed",
                "claim_support": CLAIM_SUPPORT["C9"],
                "seeds": "1 (Optuna seed 0)",
                "scope": "preliminary (single Optuna seed)",
            }
        )
    return rows


def main() -> int:
    comparison = pd.read_csv(RESULTS / "phase5_comparison.csv")
    differences = pd.read_csv(RESULTS / "phase5_differences.csv")
    rows = classification_and_trading(
        comparison[comparison["metric"] != "QLIKE (min)"], differences
    ) + volatility(comparison, differences)
    table = pd.DataFrame(rows)
    table.to_csv(RESULTS / "paper_vs_reproduced.csv", index=False)
    print(table.drop(columns=["scope"]).round(4).to_string())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
