"""Write the complete candidate table of every sweep into one curated file.

Usage (from the repository root)::

    python3 papers/contextuality_inductive_bias/utils/sweep_index.py \\
        --sweeps-root papers/contextuality_inductive_bias/outdir/sweeps \\
        --out papers/contextuality_inductive_bias/results/sweep_index.md

Reads each sweep's ``summary.json`` (written by ``summarize_sweep.py`` from
structured ``metrics.json``) and reports the declared plan (metrics,
direction, split, checkpoint, aggregation, tie tolerance, selection rule),
the coverage, every missing or INVALID run, and **every** candidate with
mean +- sample std for each declared metric. No candidate is dropped, so the
README can link here instead of to the disposable ``outdir/``.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PLAN_FIELDS = (
    "direction",
    "split",
    "checkpoint",
    "aggregation",
    "tie_tolerance",
    "selection_rule",
)


def _format_metric(aggregate: dict | None) -> str:
    if aggregate is None:
        return "n/a"
    return f"{aggregate['mean']:.4e} +- {aggregate['std']:.1e}"


def sweep_section(summary: dict) -> list[str]:
    """Markdown lines for one sweep: plan, coverage and the full candidate table."""
    plan = summary["plan"]
    missing_fields = [field for field in PLAN_FIELDS if field not in plan]
    if missing_fields:
        raise KeyError(f"{summary['sweep_id']}: plan lacks {missing_fields}")
    metrics = plan["metrics"]
    axes = sorted(
        {
            axis
            for candidate in summary["candidates"]
            for axis in candidate["grid_point"]
        }
    )
    lines = [
        f"## `{summary['sweep_id']}`",
        "",
        f"- Coverage: **{summary['coverage']}**, {summary['successful_runs']}/{summary['expected_runs']} valid runs",
        *(
            f"- {field.replace('_', ' ').capitalize()}: {plan[field]}"
            for field in PLAN_FIELDS
        ),
        f"- Metrics (dotted paths in `metrics.json`): {', '.join(f'`{m}`' for m in metrics)}",
    ]
    excluded = [
        (m["run_id"], m["status"]) for c in summary["candidates"] for m in c["missing"]
    ]
    lines.append(
        "- Missing or invalid runs: "
        + (
            "; ".join(f"`{rid}` {status}" for rid, status in excluded)
            if excluded
            else "none"
        )
    )
    lines += [
        "",
        "| "
        + " | ".join(axes)
        + " | Valid / expected | Status | "
        + " | ".join(metrics)
        + " |",
        "|" + "---|" * len(axes) + "---:|---|" + "---:|" * len(metrics),
    ]
    for candidate in summary["candidates"]:
        lines.append(
            "| "
            + " | ".join(str(candidate["grid_point"].get(axis, "")) for axis in axes)
            + f" | {candidate['successful_runs']}/{candidate['expected_runs']} | {candidate['status']} | "
            + " | ".join(_format_metric(candidate["aggregates"][m]) for m in metrics)
            + " |"
        )
    return lines + [""]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sweeps-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    summaries = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(args.sweeps_root.glob("*/summary.json"))
    ]
    if not summaries:
        raise FileNotFoundError(f"No summary.json under {args.sweeps_root}")
    lines = [
        "# Sweep index: complete candidate tables",
        "",
        "Generated by `utils/sweep_index.py` from each sweep's `summary.json`. Values are mean +- sample std (ddof = 1) over valid runs.",
        "Descriptive sweeps select no winner; tuning sweeps are resolved by `utils/select_hyperparameters.py` (`fair_tuning_selection.md`).",
        "",
        "| Sweep | Coverage | Valid / expected | Candidates |",
        "|---|---|---:|---:|",
        *(
            f"| `{s['sweep_id']}` | {s['coverage']} | {s['successful_runs']}/{s['expected_runs']} | {len(s['candidates'])} |"
            for s in summaries
        ),
        "",
    ]
    for summary in summaries:
        lines += sweep_section(summary)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"{len(summaries)} sweeps, {sum(len(s['candidates']) for s in summaries)} candidates -> {args.out}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
