md(r"""
## 3. The model in a few equations

**Quantum neuron.** For H(θ) = Σ_j θ_j H_j with spectral decomposition
H = V diag(λ) V†,

$$f_\theta(\rho) = \sum_{a} \tanh(\lambda_a/T)\,(V^\dagger\rho V)_{aa}.$$

**Gradient (exact).** The derivative of a matrix function uses the
Daleckii–Krein formula with divided differences
F_ab = (φ(λ_a) − φ(λ_b))/(λ_a − λ_b):

$$\partial_j f_\theta(\rho) = \mathrm{Tr}\big[H_j\, V\,(F\circ V^\dagger\rho V)\,V^\dagger\big].$$

**Commuting neuron (B1, the paper's baseline).** Only Z-type terms, so
H is diagonal and f(ρ) = Σ_z ⟨z|ρ|z⟩ φ(E(z)): a classical neuron applied
to the Z-measurement distribution. It cannot see X or Y information.

**The fair classical baseline (B2).** It uses the same Pauli terms H_j and
the same activation, but applies the activation *after* measuring:

$$g_\theta(\rho) = \tanh\Big(\sum_j \theta_j \langle H_j\rangle_\rho / T\Big).$$

B2 has exactly the same parameters and the same measured observables as
the quantum neuron. The only difference is "activation of the operator" vs
"activation of its expectation", so it isolates what quantization adds.
B3 is the linear model Tr[H(θ)ρ] = Σ_j θ_j ⟨H_j⟩.
""")

