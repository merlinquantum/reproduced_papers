"""Phase 5: fair-comparison tables and figure from structured artifacts.

Usage (from the repository root)::

    python3 papers/virtual_qnn/utils/compare_fair.py \
        --e5-run papers/virtual_qnn/outdir/phase5/e5_equal_shot/run_<ts> \
        --e4-run papers/virtual_qnn/outdir/phase5/e4_equal_shot_attempt2/run_<ts> \
        --sweeps-root papers/virtual_qnn/outdir/sweeps --out papers/virtual_qnn/results

Reads the equal-shot evaluation runs' ``metrics.json`` and the sweeps'
``sweep_status.json`` (for wall-clock); writes ``fair_comparison.json``,
``fair_comparison.md`` and ``fig_equal_shot.png``. Applies the decision rules
frozen in LOG.md ("Phase 5 Comparison Plan").
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

PROJECT_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_DIR.parents[1]))
sys.path.insert(0, str(PROJECT_DIR.parent))

from virtual_qnn.utils import plot_style as style  # noqa: E402

DISTANCES = [0.4, 0.45, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0, 1.25, 1.7]
TIMING_SWEEPS = [
    "e4_vqc_budget",
    "e4_vqc_baselines",
    "e4_vqc_merlin_budget_enc01",
    "e4_vqc_merlin_noiseless_enc01",
    "e5_vvqe",
    "e5_vqe_noiseless",
]


def _load_metrics(run: Path) -> dict:
    status = json.loads((run / "run_status.json").read_text())
    if status["status"] != "COMPLETED":
        raise ValueError(f"{run} is {status['status']}")
    return json.loads((run / status["metrics_path"]).read_text())


def _timing(root: Path) -> dict:
    out = {}
    for sweep in TIMING_SWEEPS:
        status = json.loads((root / sweep / "sweep_status.json").read_text())
        elapsed = [
            a["elapsed_s"]
            for r in status["runs"]
            for a in r["attempts"]
            if a["outcome"] == "COMPLETED"
        ]
        out[sweep] = {
            "median_run_s": float(np.median(elapsed)),
            "max_run_s": float(np.max(elapsed)),
            "n_runs": len(elapsed),
            "sweep_wall_clock": f"{status['started_at']} → {status['completed_at']}",
        }
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--e5-run", type=Path, required=True)
    parser.add_argument("--e4-run", type=Path, required=True)
    parser.add_argument("--sweeps-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    e5, e4 = _load_metrics(args.e5_run), _load_metrics(args.e4_run)

    # E5: equal total shot budget, RMSE vs FCI (mean over 3 seeds).
    rmse = e5["aggregated_rmse"]
    shots = [str(float(s)) for s in e5["shot_grid"]]
    e5_rows = []
    for budget in (1.0, 1.5, 2.0, 2.5):
        for s in shots:
            values = [
                rmse[f"d={d}|gamma={budget}|S={s}"]["rmse_mean"] for d in DISTANCES
            ]
            e5_rows.append(
                {
                    "budget": budget,
                    "shots": float(s),
                    "median_rmse_over_distances": float(np.median(values)),
                    "max_rmse": float(np.max(values)),
                    "min_rmse": float(np.min(values)),
                }
            )
    e5_decisions = e5["decisions"]

    # E4: equal shots per prediction, expected test accuracy (10 paired reps).
    acc = e4["aggregated_accuracy"]
    models = sorted({k.split("|S=")[0] for k in acc})
    e4_shots = [str(s) for s in e4["shot_grid"]]
    e4_rows = [
        {"model": m, "shots": s, **acc[f"{m}|S={s}"]} for m in models for s in e4_shots
    ]
    tests = e4["paired_tests"]

    report = {
        "scope": "Phase 5 fair control: trained Phase 3 (paper reproduction) and Phase 4 (MerLin adaptation) models re-evaluated at equal shot budgets; exact binomial / exact variance formulas; simulation only",
        "e5_equal_total_shots": {"rows": e5_rows, "decisions": e5_decisions},
        "e4_equal_shots_per_prediction": {"rows": e4_rows, "paired_tests": tests},
        "timing": _timing(args.sweeps_root),
        "hardware": "Apple M2 (8 cores, 16 GB), macOS, CPU only; sweeps used 6 single-threaded workers; times include process start-up",
    }
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "fair_comparison.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )

    lines = [
        "# Phase 5 — fair comparison at equal shot budgets (generated by utils/compare_fair.py)",
        "",
        "Provenance: all values are **locally executed** (no paper values in these tables). Scope: exact-formula evaluation of the trained Phase 3/4 models; simulation only.",
        "",
        "## E5 — VVQE vs VQE at equal total shots per energy estimate (RMSE vs FCI, Ha; median over 10 distances of the 3-seed mean)",
        "",
        "| S | "
        + " | ".join(f"γ={b}" for b in (1.0, 1.5, 2.0, 2.5))
        + " | VVQE better than VQE at (distances of 10): γ=1.5 / 2 / 2.5 |",
        "|---:|" + "---:|" * 5,
    ]
    for s in shots:
        cells = [
            f"{next(r['median_rmse_over_distances'] for r in e5_rows if r['budget'] == b and r['shots'] == float(s)):.4f}"
            for b in (1.0, 1.5, 2.0, 2.5)
        ]
        wins = [
            str(
                e5_decisions[f"gamma={b}|S={int(float(s))}"]["distances_virtual_better"]
            )
            for b in (1.5, 2.0, 2.5)
        ]
        lines.append(
            f"| {int(float(s)):,} | "
            + " | ".join(cells)
            + " | "
            + " / ".join(wins)
            + " |"
        )
    lines += [
        "",
        "## E4 — classifiers at equal shots per prediction (expected test accuracy, mean ± std over 10 paired reps)",
        "",
        "| Model | " + " | ".join(f"S={s}" for s in e4_shots) + " |",
        "|---|" + "---:|" * len(e4_shots),
    ]
    for m in models:
        lines.append(
            f"| {m} | "
            + " | ".join(
                f"{acc[f'{m}|S={s}']['mean']:.3f} ± {acc[f'{m}|S={s}']['std']:.3f}"
                for s in e4_shots
            )
            + " |"
        )
    lines += [
        "",
        "| Paired comparison | " + " | ".join(f"S={s}" for s in e4_shots) + " |",
        "|---|" + "---|" * len(e4_shots),
    ]
    for comparison in sorted({k.split("|S=")[0] for k in tests}):
        cells = []
        for s in e4_shots:
            q = tests[f"{comparison}|S={s}"]
            cells.append(
                f"{q['mean_difference']:+.3f} (p={q['p_value_two_sided']:.2g}){' ✓' if q['advantage_at_equal_shots'] else ''}"
            )
        lines.append(f"| {comparison} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "✓ = advantage at equal shots (paired mean difference > 0, p < 0.05).",
        "",
        "## Wall-clock (local runs)",
        "",
        "| Sweep | runs | median s/run | max s/run | sweep interval (UTC) |",
        "|---|---:|---:|---:|---|",
    ]
    for sweep, t in report["timing"].items():
        lines.append(
            f"| {sweep} | {t['n_runs']} | {t['median_run_s']:.1f} | {t['max_run_s']:.1f} | {t['sweep_wall_clock']} |"
        )
    lines += ["", f"Hardware: {report['hardware']}."]
    (args.out / "fair_comparison.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )

    style.apply_style()
    fig, (left, right) = style.plt.subplots(1, 2, figsize=(10.4, 4.0))
    for index, budget in enumerate((1.0, 1.5, 2.0, 2.5)):
        xs = [r["shots"] for r in e5_rows if r["budget"] == budget]
        ys = [r["median_rmse_over_distances"] for r in e5_rows if r["budget"] == budget]
        left.plot(
            xs,
            ys,
            color=style.SERIES[index],
            marker=style.MARKERS[index],
            label="VQE (γ = 1)" if budget == 1.0 else f"VVQE γ = {budget:g}",
        )
    left.set_xscale("log")
    left.set_yscale("log")
    left.set_xlabel("Total shots per energy estimate S")
    left.set_ylabel("RMSE vs exact energy (Ha), median over 10 bond lengths")
    left.set_title("E5: HeH⁺ energy at equal shot budget", loc="left")
    left.legend(fontsize=8)
    finite = [s for s in e4_shots if s != "inf"]
    xs = [int(s) for s in finite]
    for index, (model, label) in enumerate(
        (
            ("vqc|gamma=1.0", "Gate QC (γ = 1, 8 params)"),
            ("param_matched|gamma=1.0", "Gate QC depth 4 (γ = 1, 16 params)"),
            ("vqc|gamma=3.0", "Gate VQC γ = 3 (16 params)"),
            ("photonic|gamma=3.0", "Photonic VQC γ = 3 (MerLin adaptation)"),
        )
    ):
        means = [acc[f"{model}|S={s}"]["mean"] for s in finite]
        right.plot(
            xs,
            means,
            color=style.SERIES[index],
            marker=style.MARKERS[index],
            label=label,
        )
    photonic_one = [acc[f"photonic|gamma=1.0|S={s}"]["mean"] for s in finite]
    right.plot(
        xs,
        photonic_one,
        color=style.NEUTRAL,
        marker="x",
        linestyle=":",
        label="Photonic QC γ = 1 (MerLin adaptation)",
    )
    right.set_xscale("log")
    right.set_ylim(0.45, 1.0)
    right.set_xlabel("Measurement shots per prediction S")
    right.set_ylabel("Expected test accuracy (10 paired reps)")
    right.set_title("E4: classifiers at equal shots", loc="left")
    right.legend(fontsize=7.5, loc="upper left")
    fig.text(
        0.06,
        -0.06,
        "Scope: locally executed, exact finite-shot formulas for the paper's quasi-probability estimator applied to trained Phase 3/4 models; simulation only.",
        fontsize=8,
        color=style.TEXT_SECONDARY,
    )
    paths = style.save(fig, "fig_equal_shot", [args.out, args.e5_run, args.e4_run])
    print(
        "\n".join(
            str(p)
            for p in [
                args.out / "fair_comparison.json",
                args.out / "fair_comparison.md",
                *paths,
            ]
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
