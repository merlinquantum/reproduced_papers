"""Export every sweep's full candidate table to a durable, committed results file.

Usage::

    python3 papers/virtual_qnn/utils/export_sweep_tables.py \
        --sweeps-root papers/virtual_qnn/outdir/sweeps --out papers/virtual_qnn/results/sweep_tables.md

``outdir/`` is git-ignored, so this copies each ``summary.json`` (generated by
``utils/summarize_sweep.py`` from structured metrics) into one Markdown file:
declared plan (metric, direction, split, checkpoint, aggregation, selection
rule), successful/expected run counts, coverage classification, sweep status
(including SUPERSEDED / diagnostic labels from LOG.md) and every candidate's
mean, std, min and max at full precision.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

LABELS = {
    "e4_vqc_merlin_budget": "SUPERSEDED (invalid photonic encoding; Phase 4 Amendment 2) — excluded from conclusions",
    "e5_diag_best_of_10": "diagnostic (Phase 3 gap diagnosis H1) — not paper-accurate",
    "e5_diag_600_iterations": "diagnostic (Phase 3 gap diagnosis H2) — not paper-accurate",
    "e4_vqc_merlin_budget_enc01": "Phase 4 MerLin adaptation — not the original method",
    "e4_vqc_merlin_noiseless_enc01": "Phase 4 MerLin adaptation (noise-free control) — not the original method",
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sweeps-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    lines = [
        "# Full sweep tables (generated by utils/export_sweep_tables.py from each sweep's summary.json)",
        "",
        "Mean, population std (ddof = 0), min and max over repetitions, full precision. All sweeps are descriptive: no candidate is selected, so no winners or ties are declared.",
        "",
    ]
    for status_path in sorted(args.sweeps_root.glob("*/sweep_status.json")):
        sweep_dir = status_path.parent
        status = json.loads(status_path.read_text())
        summary = json.loads((sweep_dir / "summary.json").read_text())
        plan = summary["plan"]
        label = LABELS.get(
            status["sweep_id"], "paper-accurate (reference hyperparameters)"
        )
        lines += [
            f"## {status['sweep_id']}",
            "",
            f"- Label: {label}",
            f"- Status: {status['status']}; coverage: {summary['coverage']} ({summary['successful_runs']}/{summary['expected_runs']} runs)",
            f"- Interval (UTC): {status['started_at']} → {status['completed_at']}; paper_code_sha256 at launch: `{status['code'].get('paper_code_sha256', 'n/a')}`",
            f"- Base config: `{status['spec']['base_config']}`; repetitions: {len(status['spec']['repetitions'])}",
            f"- Metrics: {', '.join(plan['metrics'])}; direction: {plan['direction']}; split: {plan['split']}; checkpoint: {plan['checkpoint']}",
            f"- Aggregation: {plan['aggregation']}; selection rule: {plan['selection_rule']}",
            "",
        ]
        axes = sorted({k for c in summary["candidates"] for k in c["grid_point"]})
        header = (
            axes + ["runs"] + [f"{m} mean ± std [min, max]" for m in plan["metrics"]]
        )
        lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
        for c in summary["candidates"]:
            cells = [str(c["grid_point"].get(a, "")) for a in axes] + [
                f"{c['successful_runs']}/{c['expected_runs']}"
            ]
            for m in plan["metrics"]:
                a = c["aggregates"][m]
                cells.append(
                    f"{a['mean']:.6g} ± {a['std']:.3g} [{a['min']:.6g}, {a['max']:.6g}]"
                    if a
                    else "—"
                )
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
