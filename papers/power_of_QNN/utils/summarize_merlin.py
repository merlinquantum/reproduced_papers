"""Phase 04 tables and predeclared comparison criteria for the MerLin adaptation.

Usage (from papers/power_of_QNN):
    python utils/summarize_merlin.py --runs results/phase04_runs.json --phase3-runs results/phase03_runs.json --output results/phase04_tables.md

The criteria are the ones fixed in LOG.md "Phase 4 Adaptation Plan" before any MerLin run:
a gap counts as resolved when it exceeds 3 x the larger of the two draw (or seed) standard
deviations. Values are read at full precision from metrics.json.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from figure_io import load_metrics

N_INDICES = {"1e3": 0, "1e4": 3, "1e5": 6, "1e6": 10}


def _gap_rows(name_a: str, a: dict, name_b: str, b: dict) -> list[str]:
    """Rows comparing a - b at each paper n, with the 3-sigma rule."""
    rows = []
    for label, index in N_INDICES.items():
        mean_a, std_a = (
            a["normalized_effective_dimension_mean"][index],
            a["normalized_effective_dimension_std"][index],
        )
        mean_b, std_b = (
            b["normalized_effective_dimension_mean"][index],
            b["normalized_effective_dimension_std"][index],
        )
        gap, threshold = mean_a - mean_b, 3 * max(std_a, std_b)
        verdict = "resolved" if abs(gap) > threshold else "within 3 std"
        rows.append(
            f"| {name_a} − {name_b} | n={label} | {gap:+.4f} | {threshold:.4f} | {'a > b' if gap > 0 else 'a < b'}, {verdict} |"
        )
    return rows


def _effective_dimension_table(metrics: dict, title: str) -> list[str]:
    lines = [
        f"### {title}",
        "",
        "| Model | d | n=1e3 | n=1e4 | n=1e5 | n=1e6 | largest n | mean rank | frac eig < 1e-10 | tr F / d | postselection success | hardware |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, entry in metrics["models"].items():
        mean, std = (
            entry["normalized_effective_dimension_mean"],
            entry["normalized_effective_dimension_std"],
        )
        cells = " | ".join(f"{mean[i]:.4f} ± {std[i]:.4f}" for i in N_INDICES.values())
        success = [
            draw["postselection_success_mean"]
            for draw in entry["draws"]
            if "postselection_success_mean" in draw
        ]
        hardware = entry.get("hardware")
        hardware_text = (
            "n/a"
            if hardware is None
            else f"{hardware['computation_space']}, {hardware['photons']} photons / {hardware['modes']} modes"
        )
        lines.append(
            f"| {name} | {entry['d']} | {cells} | {mean[-1]:.4f} (n={metrics['n_values'][-1]:.0e}) | {entry['mean_rank_mean']:.2f} | "
            f"{entry['fraction_near_zero_mean']:.3f} | {entry['mean_trace_mean'] / entry['d']:.3e} | "
            f"{'n/a' if not success else f'{np.mean(success):.3f}'} | {hardware_text} |"
        )
    fisher = metrics["fisher"]
    return lines + [
        f"\nDraw seeds {fisher['draw_seeds']}; {fisher['num_thetas']} theta x {fisher['num_inputs']} inputs; theta ~ U[{fisher['theta_low']}, {fisher['theta_high']:.4g}].\n"
    ]


def _trace_slope(entries: list[dict]) -> float:
    sizes = np.asarray([entry["input_size"] for entry in entries])
    per_parameter = np.asarray(
        [entry["mean_trace_mean"] / entry["d"] for entry in entries]
    )
    return float(np.exp(np.polyfit(sizes, np.log(per_parameter), 1)[0]))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=Path, required=True)
    parser.add_argument("--phase3-runs", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    runs = {k: Path(v) for k, v in json.loads(args.runs.read_text()).items()}
    phase3 = {k: Path(v) for k, v in json.loads(args.phase3_runs.read_text()).items()}
    m = {k: load_metrics(v) for k, v in runs.items()}
    p3 = {
        k: load_metrics(phase3[k])
        for k in (
            "effdim_d40_original",
            "topology_search_d40_classical",
            "spectrum_scaling_original",
            "training_iris_original",
        )
    }

    lines = [
        "# power_of_QNN Phase 04 (MerLin adaptation) tables",
        "",
        "MerLin **adaptation**, not the paper's model. Generated by `utils/summarize_merlin.py` from: "
        + ", ".join(f"`{k}` = `{v}`" for k, v in runs.items())
        + ".",
        "",
    ]
    titles = {
        "effdim_d40_merlin": "Fig. 2/3a counterpart, threshold detection, theta ~ U[0,1]",
        "effdim_d40_merlin_unbunched": "Ablation: UNBUNCHED postselection",
        "effdim_d40_merlin_phase_domain": "Ablation: theta ~ U[0, 2pi]",
        "spectrum_scaling_merlin": "Fig. 9 counterpart, s_in = 6, 8, 10",
    }
    for key, title in titles.items():
        lines += _effective_dimension_table(m[key], f"{title} (`{key}`)")

    hard, easy = (
        m["effdim_d40_merlin"]["models"]["photonic_hard"],
        m["effdim_d40_merlin"]["models"]["photonic_easy"],
    )
    classical = p3["effdim_d40_original"]["models"]["classical_4442"]
    qnn = p3["effdim_d40_original"]["models"]["qnn"]
    best = max(
        p3["topology_search_d40_classical"]["candidates"],
        key=lambda c: (c["mean_rank"], c["selection_value"]),
    )
    lines += [
        "### Predeclared criteria (LOG.md Phase 4 Adaptation Plan)",
        "",
        "Gap = a − b in normalized effective dimension; threshold = 3 × max(std_a, std_b) over draws.",
        "",
        "| Comparison | n | gap | 3-std threshold | outcome |",
        "|---|---|---|---|---|",
    ]
    lines += _gap_rows("photonic_hard", hard, "photonic_easy", easy)
    lines += _gap_rows("photonic_hard", hard, "classical_4442 (Phase 3)", classical)
    lines += _gap_rows("photonic_hard", hard, "qubit QNN (Phase 3)", qnn)
    lines.append(
        f"\nBest searched classical topology (Phase 3, {best['sizes']}): normalized effective dimension at n=1e5 = {best['selection_value']:.4f}; "
        f"photonic_hard at n=1e5 = {hard['normalized_effective_dimension_mean'][6]:.4f} (per-candidate draw std not stored; difference {hard['normalized_effective_dimension_mean'][6] - best['selection_value']:+.4f}).\n"
    )

    scaling = m["spectrum_scaling_merlin"]["models"]
    lines += [
        "### Encoding effect across sizes (photonic hard − easy)",
        "",
        "| Comparison | n | gap | 3-std threshold | outcome |",
        "|---|---|---|---|---|",
    ]
    for size in (6, 8, 10):
        lines += _gap_rows(
            f"hard s{size}",
            scaling[f"photonic_hard_s{size}"],
            f"easy s{size}",
            scaling[f"photonic_easy_s{size}"],
        )
    photonic_hard_family = [hard] + [scaling[f"photonic_hard_s{s}"] for s in (6, 8, 10)]
    photonic_easy_family = [easy] + [scaling[f"photonic_easy_s{s}"] for s in (6, 8, 10)]
    qubit3 = p3["spectrum_scaling_original"]["models"]
    qubit_hard = [qnn] + [qubit3[f"qnn_s{s}"] for s in (6, 8, 10)]
    qubit_easy = [p3["effdim_d40_original"]["models"]["easy_qnn"]] + [
        qubit3[f"easy_qnn_s{s}"] for s in (6, 8, 10)
    ]
    lines += [
        "",
        "### Fisher scale vs input size (barren-plateau diagnostic): tr F / d decay factor per added input (log-linear fit, s_in = 4..10)",
        "",
        "| Model family | factor per input |",
        "|---|---|",
        f"| photonic hard | {_trace_slope(photonic_hard_family):.3f} |",
        f"| photonic easy | {_trace_slope(photonic_easy_family):.3f} |",
        f"| qubit QNN (Phase 3) | {_trace_slope(qubit_hard):.3f} |",
        f"| qubit easy (Phase 3) | {_trace_slope(qubit_easy):.3f} |",
        "",
    ]

    training = m["training_iris_merlin"]["models"]
    qubit_training = p3["training_iris_original"]["models"]
    lines += [
        "### Iris training (Fig. 3b counterpart; d=8; 100 seeds)",
        "",
        "| Model | final loss | final train acc | frac CE ≤ 0.3 | Fisher-Rao norm | mean ‖θ‖² |",
        "|---|---|---|---|---|---|",
    ]
    for name, entry in list(training.items()) + [
        (f"{k} (Phase 3)", v) for k, v in qubit_training.items()
    ]:
        lines.append(
            f"| {name} | {entry['final_loss_mean']:.4f} ± {entry['final_loss_std']:.4f} | {entry['final_accuracy_mean']:.3f} | {entry['fraction_reaching_threshold']:.2f} | "
            f"{entry['fisher_rao_norm_mean']:.2f} | {entry['final_theta_norm_squared_mean']:.1f} |"
        )
    seeds = len(m["training_iris_merlin"]["seeds"])
    lines += [
        "",
        "Trainability criterion (difference in mean final loss vs its standard error, sqrt(s_a²/N + s_b²/N)):",
        "",
        "| Comparison | difference | standard error | outcome |",
        "|---|---|---|---|",
    ]
    pairs = [
        (
            "photonic_hard",
            training["photonic_hard"],
            "classical_41112 (Phase 3)",
            qubit_training["classical_41112"],
        ),
        (
            "photonic_hard",
            training["photonic_hard"],
            "photonic_easy",
            training["photonic_easy"],
        ),
        (
            "photonic_hard",
            training["photonic_hard"],
            "qubit QNN (Phase 3)",
            qubit_training["qnn"],
        ),
    ]
    for name_a, a, name_b, b in pairs:
        difference = a["final_loss_mean"] - b["final_loss_mean"]
        error = float(
            np.sqrt(a["final_loss_std"] ** 2 / seeds + b["final_loss_std"] ** 2 / seeds)
        )
        lines.append(
            f"| {name_a} − {name_b} | {difference:+.4f} | {error:.4f} | {'lower' if difference < 0 else 'higher'}, {'resolved' if abs(difference) > error else 'not resolved'} |"
        )
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
