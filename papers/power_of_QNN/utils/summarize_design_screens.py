"""Full candidate tables of every Phase 04 photonic design search (Amendments 2-5).

Usage (from papers/power_of_QNN):
    python utils/summarize_design_screens.py --runs results/phase04_design_runs.json --output results/phase04_design_screens.md

``--runs`` maps a label to ``{"run": <run dir>, "role": <text>}``. Fisher runs list every
model's normalized effective dimension (mean ± std over draws) at n = 1e3, 1e5 and 1e6 and
its mean F_hat rank. Fair-comparison screening runs list every candidate's mean final
validation CE per learning rate and the selected lr. Values are read at full precision from
metrics.json; the selection rules themselves are stated in LOG.md for each amendment.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from figure_io import PAPER_N, load_metrics
from power_of_QNN.lib.display_names import model_label

N_COLUMNS = {
    "1e3": PAPER_N.index(1000),
    "1e5": PAPER_N.index(100000),
    "1e6": PAPER_N.index(1000000),
}


def _named(name: str) -> str:
    """Readable model name followed by the code name its run artifacts use."""
    return f"{model_label(name, detailed=True)} (`{name}`)"


def _search_title(label: str) -> str:
    """Name a run by its design search; LOG.md records search k as Amendment k + 1."""
    return re.sub(
        r"Amendment (\d)",
        lambda match: (
            f"Design search {int(match.group(1)) - 1} (LOG.md Amendment {match.group(1)})"
        ),
        label,
    )


def _fisher_rows(metrics: dict) -> list[str]:
    lines = [
        "| Model | Draws | "
        + " | ".join(f"ED n={label}" for label in N_COLUMNS)
        + " | Mean rank |",
        "|---|---|" + "---:|" * len(N_COLUMNS) + "---:|",
    ]
    for name, entry in metrics["models"].items():
        means = entry["normalized_effective_dimension_mean"]
        stds = entry["normalized_effective_dimension_std"]
        lines.append(
            f"| {_named(name)} | {[draw['draw_seed'] for draw in entry['draws']]} | "
            + " | ".join(f"{means[i]:.4f} ± {stds[i]:.4f}" for i in N_COLUMNS.values())
            + f" | {entry['mean_rank_mean']:.2f} |"
        )
    return lines


def _training_rows(metrics: dict) -> list[str]:
    split = metrics["comparison"]["selection_split"]
    lr_grid = metrics["comparison"]["lr_grid"]
    lines = [
        f"| Model | {' | '.join(f'{split} CE at lr {lr:g}' for lr in lr_grid)} | Selected lr (tied) |",
        "|---|" + "---:|" * len(lr_grid) + "---|",
    ]
    for name, entry in metrics["models"].items():
        tied = ", ".join(f"{lr:g}" for lr in entry["tied_lrs"])
        lines.append(
            f"| {_named(name)} | "
            + " | ".join(f"{entry['grid_mean_loss'][str(lr)]:.4f}" for lr in lr_grid)
            + f" | {entry['selected_lr']:g} ({tied}) |"
        )
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    runs = json.loads(args.runs.read_text(encoding="utf-8"))
    lines = [
        "# Phase 04 photonic design searches: every candidate",
        "",
        "Generated by `utils/summarize_design_screens.py` from metrics.json. Normalized effective",
        "dimension uses gamma = 1 and 100 theta x 100 inputs per draw. Selection rules and verdicts",
        "are in LOG.md, where design searches 1-4 are recorded as Amendments 2-5. Every run is",
        "COMPLETED. Each model shows its readable name and, in brackets, the code name used by",
        "configs and run artifacts.",
        "",
    ]
    for label, spec in runs.items():
        run_dir = Path(spec["run"])
        metrics = load_metrics(run_dir)
        lines += [
            f"## {_search_title(label)} (`{run_dir.as_posix()}`)",
            "",
            spec["role"],
            "",
        ]
        if "comparison" in metrics:
            lines += _training_rows(metrics)
        else:
            theta = metrics["fisher"]
            lines.append(f"theta ~ U[{theta['theta_low']:g}, {theta['theta_high']:g}]")
            lines.append("")
            lines += _fisher_rows(metrics)
        lines.append("")
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.output} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
